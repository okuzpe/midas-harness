#!/usr/bin/env node
// skill-registry.mjs — generate <paths.engine>/skill-registry.md (exact SKILL.md paths).
//
// Index, not summary: agents pass matched Path rows to sub-agents. No cache sidecar —
// doctor/align recompute and compare (same pattern as gates.json / checks.json).
//
// Delegator column (path-readability, NOT Skill-tool invocation):
//   - yes — builders/scouts may match and READ this SKILL.md when the parent passes its Path.
//           `disable-model-invocation: true` still forbids Skill-tool / auto slash invoke.
//   - orchestrator-only — phase gates + install/sync/high-stakes audits; human slash / stage table
//           only — never free-picked by builders.
//
// Usage:
//   node scripts/skill-registry.mjs              # write harness/skill-registry.md
//   node scripts/skill-registry.mjs --check       # exit 1 if on-disk drifts from recomputed

import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { resolvePaths } from './paths.mjs';
import { parseFrontmatter } from './skill-quality-check.mjs';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(HERE, '..');

/**
 * Skills that must never be free-picked by builders/scouts (stage table + human slash only).
 * Keep this list SMALL — phase gates, install/sync, and high-stakes audits.
 * Phase-7 procedures (verify, qa, progress, explore, lean-review, …) are Delegator: yes so
 * parents can path-pass their SKILL.md for reading without Skill-tool invocation.
 * Keep in sync with STAGE_ROWS in scripts/stage-command-table.mjs (→ generated
 * harness/stage-command-table.yaml) + AGENTS.md Safety for gate owners.
 */
export const ORCHESTRATOR_ONLY_ALLOWLIST = new Set([
  // Pipeline phase gates 0–8
  'idea-intake',
  'contextualize',
  'market-research',
  'business-plan',
  'choose-architecture',
  'define-conventions',
  'plan-sprints',
  'start-sprint',
  'close-sprint',
  // Install / sync / engine lifecycle
  'midas-init',
  'midas-adopt',
  'midas-update',
  'midas-doctor',
  'midas-align',
  'midas-precommit',
  'midas-bundle',
  // High-stakes standing audits (orchestrate-owned)
  'midas-tribunal',
  'midas-security-audit',
]);

/**
 * Escape pipe cells for markdown tables.
 * @param {string} value
 */
function escapeCell(value) {
  return String(value || '')
    .replace(/\r?\n/g, ' ')
    .replace(/\|/g, '\\|')
    .trim();
}

/**
 * @param {string} root
 * @param {{ engine?: string }} [paths]
 * @returns {{ id: string, name: string, description: string, scope: string, delegator: string, path: string }[]}
 */
export function collectSkillRegistryRows(root, paths) {
  const p = paths || resolvePaths(root);
  const skillsDir = join(root, p.engine, 'skills');
  if (!existsSync(skillsDir)) return [];

  const rows = [];
  for (const ent of readdirSync(skillsDir, { withFileTypes: true })) {
    if (!ent.isDirectory()) continue;
    const skillPath = join(skillsDir, ent.name, 'SKILL.md');
    if (!existsSync(skillPath)) continue;
    const text = readFileSync(skillPath, 'utf8');
    const fm = parseFrontmatter(text) || {};
    const id = ent.name;
    const name = fm.name || id;
    const description = fm.description || '';
    // Delegator is path-readability only — do NOT fold disable-model-invocation into this column.
    const orchestratorOnly = ORCHESTRATOR_ONLY_ALLOWLIST.has(id);
    // Engine-relative path so the same registry works in classic (`harness/`) and install
    // (`.harness/engine/`) layouts — agents resolve via `<paths.engine>/` + Path.
    const relPath = `skills/${id}/SKILL.md`;
    rows.push({
      id,
      name,
      description,
      scope: 'engine',
      delegator: orchestratorOnly ? 'orchestrator-only' : 'yes',
      path: relPath,
    });
  }
  rows.sort((a, b) => a.name.localeCompare(b.name));
  return rows;
}

/**
 * @param {{ id: string, name: string, description: string, scope: string, delegator: string, path: string }[]} rows
 * @param {{ engineRel?: string }} [opts]
 */
export function formatSkillRegistryMarkdown(rows, opts = {}) {
  const engineRel = opts.engineRel || 'harness';
  const lines = [
    '<!-- GENERATED by scripts/skill-registry.mjs — do not hand-edit; run `node scripts/skill-registry.mjs` or `npm run align`. -->',
    '',
    '# Skill registry',
    '',
    'Machine index of Midas-owned skills. **Human router:** `docs/skills.md` (slash-name catalog).',
    'When delegating, match against this table and pass a **subset** of exact `Path` values — never dump the whole registry into a prompt. Prefer `Delegator: yes`.',
    '',
    '**Delegator meaning:** `yes` = parents may path-pass this `SKILL.md` for the worker to **read**. It does **not** authorize Skill-tool or auto slash invoke when `disable-model-invocation: true`. `orchestrator-only` = phase gates / install-sync / high-stakes audits — human slash or stage table only.',
    '',
    'Resolve each Path as `<paths.engine>/<Path>` (e.g. `harness/skills/…` in the engine repo, `.harness/engine/skills/…` in installs).',
    '',
    `Source: \`${engineRel}/skills/*/SKILL.md\`. v1 indexes engine skills only (no project/user overlays).`,
    '',
    '| Skill | Trigger / description | Scope | Delegator | Path |',
    '| --- | --- | --- | --- | --- |',
  ];
  for (const r of rows) {
    lines.push(
      `| \`${escapeCell(r.name)}\` | ${escapeCell(r.description)} | ${escapeCell(r.scope)} | ${escapeCell(r.delegator)} | \`${escapeCell(r.path)}\` |`,
    );
  }
  lines.push('');
  return `${lines.join('\n')}\n`;
}

/**
 * @param {string} root
 * @param {{ engine?: string }} [paths]
 */
export function computeSkillRegistryMarkdown(root, paths) {
  const p = paths || resolvePaths(root);
  const rows = collectSkillRegistryRows(root, p);
  return formatSkillRegistryMarkdown(rows, { engineRel: p.engine.replace(/\\/g, '/') });
}

/**
 * @param {string} root
 * @param {{ engine?: string }} [paths]
 */
export function skillRegistryPath(root, paths) {
  const p = paths || resolvePaths(root);
  return join(root, p.engine, 'skill-registry.md');
}

/**
 * Write the registry under the engine tree.
 * @param {string} [root]
 * @param {{ engine?: string }} [paths]
 */
export function writeSkillRegistry(root = ROOT, paths) {
  const p = paths || resolvePaths(root);
  const abs = skillRegistryPath(root, p);
  mkdirSync(dirname(abs), { recursive: true });
  const md = computeSkillRegistryMarkdown(root, p);
  writeFileSync(abs, md, 'utf8');
  return abs.slice(root.length + 1).replace(/\\/g, '/');
}

/**
 * Compare on-disk registry to recomputed content.
 * @returns {{ ok: boolean, path: string, reason?: string }}
 */
export function checkSkillRegistry(root = ROOT, paths) {
  const p = paths || resolvePaths(root);
  const abs = skillRegistryPath(root, p);
  const rel = abs.slice(root.length + 1).replace(/\\/g, '/');
  if (!existsSync(abs)) {
    return { ok: false, path: rel, reason: 'missing' };
  }
  const expected = computeSkillRegistryMarkdown(root, p);
  const actual = readFileSync(abs, 'utf8');
  if (actual !== expected) {
    return { ok: false, path: rel, reason: 'drift' };
  }
  return { ok: true, path: rel };
}

const invokedDirectly =
  process.argv[1] &&
  resolve(process.argv[1]) === resolve(fileURLToPath(import.meta.url));

if (invokedDirectly) {
  const checkOnly = process.argv.includes('--check');
  if (checkOnly) {
    const result = checkSkillRegistry(ROOT);
    if (!result.ok) {
      console.error(`skill-registry: ${result.path} ${result.reason} — run \`node scripts/skill-registry.mjs\``);
      process.exit(1);
    }
    console.log(`skill-registry: ok ${result.path}`);
    process.exit(0);
  }
  const rel = writeSkillRegistry(ROOT);
  const rows = collectSkillRegistryRows(ROOT);
  console.log(`skill-registry: wrote ${rel} (${rows.length} skills)`);
}
